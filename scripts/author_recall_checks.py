def main() -> int:
    written = 0
    missing: list[str] = []
    for chapter_id, checks in sorted(CHECKS.items()):
        path = SPECS / f"{chapter_id}.json"
        if not path.exists():
            missing.append(chapter_id)
            continue
        spec = json.loads(path.read_text())
        spec["exam_recall_checks"] = checks
        path.write_text(json.dumps(spec, ensure_ascii=False, indent=2) + "\n")
        written += 1

    if missing:
        print(f"no spec for {len(missing)} chapters: {', '.join(missing)}")
        return 1
    total = sum(len(checks) for checks in CHECKS.values())
    print(f"wrote recall checks for {written} chapters: {total} checks")
    return 0


